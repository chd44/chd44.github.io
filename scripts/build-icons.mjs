// Generates vendor/lucide-icons.js: only the Lucide icons index.html uses, plus a
// drop-in window.lucide.createIcons(). The full Lucide bundle is ~360 KB for ~30 icons.
// Run `npm run icons` after adding or renaming a data-lucide icon in index.html.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { icons } from 'lucide';

const root = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
const html = await readFile(path.join(root, 'index.html'), 'utf8');
const names = [...new Set([...html.matchAll(/data-lucide="([^"]+)"/g)].map(match => match[1]))].sort();
const toPascalCase = name => name.replace(/(\w)(\w*)(_|-|\s*)/g, (_, first, rest) => first.toUpperCase() + rest.toLowerCase());

const subset = {};
const missing = [];
for (const name of names) {
  const node = icons[toPascalCase(name)];
  if (!node) { missing.push(name); continue; }
  subset[name] = node[2];
}
if (missing.length) throw new Error('Unknown Lucide icon(s) in index.html: ' + missing.join(', '));

const { version } = JSON.parse(await readFile(path.join(root, 'node_modules/lucide/package.json'), 'utf8'));
const output = `/*! Lucide v${version} icon subset | ISC License | see vendor/LUCIDE-LICENSE.txt
 * Generated by scripts/build-icons.mjs from the icons used in index.html. Do not edit by hand. */
(() => {
  'use strict';
  const icons = ${JSON.stringify(subset)};
  const base = { xmlns: 'http://www.w3.org/2000/svg', width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  const build = (tag, attrs, children) => {
    const element = document.createElementNS('http://www.w3.org/2000/svg', tag);
    Object.keys(attrs).forEach(name => element.setAttribute(name, String(attrs[name])));
    (children || []).forEach(([childTag, childAttrs, grandchildren]) => element.appendChild(build(childTag, childAttrs, grandchildren)));
    return element;
  };
  function createIcons({ attrs = {}, nameAttr = 'data-lucide' } = {}) {
    document.querySelectorAll('[' + nameAttr + ']').forEach(element => {
      const name = element.getAttribute(nameAttr);
      const children = icons[name];
      if (!children) { console.warn(name + ' is not in vendor/lucide-icons.js; run npm run icons.'); return; }
      const own = {};
      Array.from(element.attributes).forEach(attribute => { own[attribute.name] = attribute.value; });
      const classes = ['lucide', 'lucide-' + name].concat((own.class || '').split(' '), (attrs.class || '').split(' '))
        .map(item => item.trim()).filter((item, index, list) => item && list.indexOf(item) === index);
      const merged = Object.assign({}, base, { 'data-lucide': name }, attrs, own, { class: classes.join(' ') });
      element.parentNode && element.parentNode.replaceChild(build('svg', merged, children), element);
    });
  }
  window.lucide = { createIcons, icons: Object.keys(icons) };
})();
`;
await writeFile(path.join(root, 'vendor/lucide-icons.js'), output);
console.log('vendor/lucide-icons.js: ' + names.length + ' icons, ' + Buffer.byteLength(output) + ' bytes');
